"""Write SOURCES.md: one row per processed file with its sources (URL, download date, licence)
and the script that produced it. Built from config/sources.json and data/raw/MANIFEST.csv."""
from __future__ import annotations

import csv
import json

from common import CONFIG, PROC, RAW, ROOT

PRODUCTS = [
    ("data/processed/crosswalk.csv", ["situas", "istat_codes"], "scripts/crosswalk.py"),
    ("data/processed/comuni.gpkg, comuni_attributes.csv", ["istat_boundaries", "situas"], "scripts/crosswalk.py"),
    ("data/processed/names/names_<election>.csv", ["eligendo", "situas"], "scripts/names.py"),
    ("data/processed/tiles.gpkg, weights.csv", ["istat_boundaries", "popgrid"], "scripts/grid.py"),
    ("data/processed/elections/<election>_*.csv", ["eligendo"], "scripts/eligendo.py, scripts/elections.py"),
    ("data/processed/politics/*.csv", ["eligendo", "ches", "popgrid"], "scripts/political.py"),
    ("data/processed/terrain_tiles.csv, terrain_comuni.csv", ["tinitaly", "luisa"], "scripts/terrain.py"),
    ("data/processed/cities.csv, comune_sll.csv", ["sll"], "scripts/layers.py"),
    ("data/processed/hazards_tiles.csv, hazards_comuni.csv", ["ingv", "ispra"], "scripts/layers.py"),
    ("data/processed/wonders.csv", ["unesco", "ports"], "scripts/layers.py"),
    ("data/processed/tiles_socio.csv, comuni_socio.csv, socio_national.json", ["istat_pop", "mef", "census", "asia"], "scripts/socio.py"),
    ("web/data/*.json", ["eligendo", "ches", "istat_pop", "mef", "census", "asia", "tinitaly", "luisa", "ingv", "ispra", "sll", "unesco", "ports"], "scripts/export.py"),
    ("tests (check only)", ["ondata2022"], "tests/test_gates.py"),
]


def main():
    src = json.loads((CONFIG / "sources.json").read_text())
    man = list(csv.DictReader(open(RAW / "MANIFEST.csv")))
    out = ["# Sources", "", "Generated by `scripts/sources_md.py` from `config/sources.json` and `data/raw/MANIFEST.csv`. "
           "Raw files are not in git; `make download` fetches them again and checks them into the manifest with a SHA-256.", "",
           "## Processed files", "", "| File | Sources | Script |", "|---|---|---|"]
    for f, ss, sc in PRODUCTS:
        out.append(f"| `{f}` | {', '.join(f'[{k}](#{k})' for k in ss)} | `{sc}` |")
    out += ["", "## Sources", ""]
    for k, s in src.items():
        files = [m for m in man if m["path"].startswith(s["raw"].replace("data/raw/", ""))]
        dates = sorted({m["downloaded"] for m in files})
        out += [f"### {k}", "", f"- **{s['name']}** — {s['publisher']}", f"- URL: {s['url']}", f"- Licence: {s['licence']}",
                f"- Vintage: {s['vintage']}", f"- Raw files: `{s['raw']}` ({len(files)} files, downloaded {', '.join(dates) or 'n/a'})",
                f"- Used by: `{s['script']}`", ""]
    out += ["## Raw files", "", "| Path | Bytes | SHA-256 | Downloaded | URL |", "|---|---:|---|---|---|"]
    for m in man:
        out.append(f"| `{m['path']}` | {int(m['bytes']):,} | `{m['sha256'][:12]}…` | {m['downloaded']} | {m['url']} |")
    (ROOT / "SOURCES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("[civ] SOURCES.md written")


if __name__ == "__main__":
    main()
